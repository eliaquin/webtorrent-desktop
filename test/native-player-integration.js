/* globals document, window, getComputedStyle */
const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { execFileSync } = require('child_process')
const { _electron } = require('playwright')
const { findRuntime } = require('../src/main/vlc-runtime')

async function main () {
  if (!findRuntime() || !fs.existsSync(path.join(__dirname, '../build/native', `vlc-${process.arch}.node`))) {
    throw new Error('Native integration requires macOS, VLC 3 and npm run build')
  }
  const root = path.join(__dirname, '..')
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'webtorrent-native-'))
  let application
  let page
  try {
    const downloads = path.join(directory, 'Downloads')
    fs.mkdirSync(downloads)
    const subtitles = path.join(directory, 'English.srt')
    fs.writeFileSync(subtitles, '1\n00:00:00,000 --> 00:00:29,000\nNative embedded subtitle\n')
    const video = path.join(downloads, 'native fixture.mkv')
    execFileSync('ffmpeg', ['-nostdin', '-v', 'error', '-f', 'lavfi', '-i', 'color=color=blue:size=640x360:rate=30:duration=30',
      '-f', 'lavfi', '-i', 'sine=duration=30', '-f', 'lavfi', '-i', 'sine=frequency=880:duration=30', '-i', subtitles,
      '-map', '0:v', '-map', '1:a', '-map', '2:a', '-map', '3:0', '-c:v', 'libx264', '-c:a', 'ac3', '-c:s', 'ass',
      '-metadata:s:a:0', 'language=eng', '-metadata:s:a:1', 'language=spa', '-metadata:s:s:0', 'language=eng', video])
    const prefs = { downloadPath: downloads, isFileHandler: false, videoEngine: 'vlc', openExternalPlayer: false, externalPlayerPath: '', startup: false, soundNotifications: false, autoAddTorrents: false, torrentsFolderPath: '', highestPlaybackPriority: true, globalTrackers: [] }
    fs.writeFileSync(path.join(directory, 'config.json'), JSON.stringify({ version: '0.25.0', prefs, torrents: [], torrentsToResume: [] }))
    const executablePath = process.env.WEBTORRENT_PACKAGED_APP || require('electron')
    application = await _electron.launch({ executablePath, args: process.env.WEBTORRENT_PACKAGED_APP ? [] : [root], env: { ...process.env, NODE_ENV: 'test', WEBTORRENT_TEST_DIR: directory } })
    application.process().stderr.on('data', chunk => { if (process.env.NATIVE_DEBUG) process.stderr.write(chunk) })
    page = application.windows().find(page => page.url().endsWith('/main.html')) || await application.firstWindow()
    page.setDefaultTimeout(30000)
    page.on('pageerror', error => console.error('Renderer error:', error))
    await page.waitForSelector('.app')
    async function inMain (action, arg) {
      return application.evaluate((electron, { action, arg }) => {
        const root = electron.app.getAppPath()
        const fromProject = process.getBuiltinModule('module').createRequire(root + '/package.json')
        const player = fromProject(root + '/build/main/native-player').getPlayer()
        if (action === 'snapshot') return player.bridge?.snapshot()
        if (action === 'session') return player.session?.id
        if (action === 'missing-runtime') { player.runtime = () => null; return }
        if (action === 'command') return player.command(...arg)
        if (action === 'dispatch') return fromProject(root + '/build/main/windows').main.dispatch(...arg)
        if (action === 'sources') return electron.desktopCapturer.getSources({ types: ['window'], thumbnailSize: { width: 800, height: 500 } }).then(sources => sources.map(source => ({ name: source.name, png: source.thumbnail.toPNG().toString('base64') })))
      }, { action, arg })
    }
    const dispatch = (...args) => inMain('dispatch', args)
    async function wait (predicate) {
      const start = Date.now()
      while (Date.now() - start < 30000) {
        const snapshot = await inMain('snapshot')
        if (snapshot && predicate(snapshot)) return snapshot
        await new Promise(resolve => setTimeout(resolve, 100))
      }
      throw new Error('Native playback timed out: ' + JSON.stringify(await inMain('snapshot')))
    }
    assert((await page.evaluate(() => window.webtorrent.invoke('native:player-available'))).available)
    await dispatch('showCreateTorrent', [video])
    await page.getByRole('button', { name: 'Show advanced settings...' }).click()
    await page.getByRole('textbox', { name: 'Trackers' }).fill('')
    await page.getByRole('button', { name: 'Create Torrent', exact: true }).click()
    await page.waitForSelector('.torrent .play')
    await page.locator('.torrent .play').click()
    await page.waitForSelector('.native-video-surface')
    let snapshot = await wait(s => s.state === 3 && s.currentTime > 1 && s.subtitleTracks.length && s.audioTracks.length === 2)
    console.log('Native snapshot:', JSON.stringify(snapshot))
    assert.strictEqual(await page.locator('video').count(), 0, 'VLC replaces the HTML video decoder')
    assert(snapshot.displayedFrames > 0, 'libVLC displays actual video frames')
    assert.strictEqual(snapshot.width, 640)
    assert(!fs.existsSync(path.join(directory, 'AudioCache')), 'AC-3 plays natively without audio conversion')
    const session = await inMain('session')
    await assert.rejects(page.evaluate(() => window.webtorrent.invoke('native:player-open', { requestId: 'invalid', url: 'https://example.com/video.mp4', paused: false })))
    await assert.rejects(page.evaluate(session => window.webtorrent.invoke('native:player-command', session, 'volume', Infinity), session))
    assert.strictEqual(await page.evaluate(() => window.webtorrent.invoke('native:player-command', 'stale', 'seek', 3)), false, 'stale sessions cannot control the next file')
    await page.getByRole('button', { name: 'Pause', exact: true }).click()
    snapshot = await wait(s => s.state === 4)
    const pausedTime = snapshot.currentTime
    await new Promise(resolve => setTimeout(resolve, 500))
    assert(Math.abs((await inMain('snapshot')).currentTime - pausedTime) < 0.1, 'pause stops the native clock')
    await dispatch('skip', -10)
    await wait(s => s.currentTime < 0.2)
    assert.strictEqual(await inMain('session'), session, 'skipping before the start keeps the native session active')
    assert.strictEqual(await page.locator('.native-video-surface').count(), 1)
    await dispatch('skipTo', 5)
    await wait(s => Math.abs(s.currentTime - 5) < 0.2)
    await dispatch('setVolume', 0.25)
    await wait(s => s.volume === 0.25)
    await dispatch('changePlaybackRate', 1)
    await wait(s => s.rate === 1.25)
    await dispatch('selectAudioTrack', 1)
    await wait(s => s.audioTrack === snapshot.audioTracks[1].id)
    await dispatch('selectSubtitle', 0)
    await wait(s => s.subtitleTrack === snapshot.subtitleTracks[0].id)
    await dispatch('selectSubtitle', -1)
    await wait(s => s.subtitleTrack === -1)
    await dispatch('addSubtitles', [path.join(directory, 'Missing.srt')], true)
    await page.waitForFunction(() => document.querySelector('.error-popover.visible')?.textContent.includes('Could not load subtitle file'))
    assert.strictEqual(await inMain('session'), session, 'a missing subtitle does not switch video engines')
    await dispatch('dismissErrors')
    const external = path.join(directory, 'External.srt')
    fs.writeFileSync(external, '1\n00:00:00,000 --> 00:00:29,000\nNative external subtitle\n')
    await dispatch('addSubtitles', [external], true)
    await page.getByRole('button', { name: 'Play', exact: true }).click()
    await wait(s => s.state === 3 && s.subtitleTracks.length === 2 && s.subtitleTrack >= 0)
    await dispatch('toggleFullScreen', true)
    await page.waitForSelector('.app.is-fullscreen')
    await dispatch('toggleFullScreen', false)
    await page.waitForSelector('.app:not(.is-fullscreen)')
    if (process.env.NATIVE_SCREENSHOT_PATH) {
      const sources = await inMain('sources')
      const source = sources.find(source => source.name.includes('native fixture'))
      if (!source) throw new Error('Native player window was not captured')
      fs.writeFileSync(process.env.NATIVE_SCREENSHOT_PATH, Buffer.from(source.png, 'base64'))
    }
    await dispatch('backToList')
    await page.waitForSelector('.media-shelf')
    for (let i = 0; i < 100 && await inMain('session'); i++) await new Promise(resolve => setTimeout(resolve, 50))
    assert(!await inMain('session'), 'closing the player releases its native session')
    assert.strictEqual(await inMain('command', [session, 'seek', 5]), false)
    assert((await page.evaluate(() => getComputedStyle(document.querySelector('.app')).backgroundColor)).startsWith('rgb('), 'library background is opaque again')
    await dispatch('preferences')
    await page.getByLabel('Video player').selectOption('chromium')
    await page.waitForFunction(() => document.querySelector('[aria-label="Video player"]')?.value === 'chromium')
    for (let i = 0; i < 100 && JSON.parse(fs.readFileSync(path.join(directory, 'config.json'))).prefs.videoEngine !== 'chromium'; i++) await new Promise(resolve => setTimeout(resolve, 25))
    assert.strictEqual(JSON.parse(fs.readFileSync(path.join(directory, 'config.json'))).prefs.videoEngine, 'chromium', 'player choice is persisted')
    await dispatch('backToList')
    await page.locator('.torrent .play').click()
    await page.waitForFunction(() => document.querySelector('.letterbox video')?.currentTime > 0)
    assert.strictEqual(await page.locator('.native-video-surface').count(), 0, 'choosing the built-in player keeps native playback off')
    await dispatch('skipTo', 5)
    await page.waitForFunction(() => document.querySelector('.letterbox video')?.currentTime >= 5)
    await dispatch('pause')
    await dispatch('backToList')
    await dispatch('updatePreferences', 'videoEngine', 'vlc')
    await inMain('missing-runtime')
    await page.locator('.torrent .play').click()
    await page.waitForFunction(() => document.querySelector('.audio-conversion-notice')?.textContent.includes('Native VLC could not play'))
    await page.waitForFunction(() => document.querySelector('.letterbox video')?.readyState >= 2)
    await page.waitForFunction(() => document.querySelector('.letterbox video')?.currentTime >= 5, null, { timeout: 2000 })
    assert(!await inMain('session'), 'missing VLC falls back without leaving a native session alive')
    console.log('Native integration passed: torrent HTTP playback, AC-3, embedded/external subtitles, audio tracks, pause, seek, volume, speed, fullscreen, IPC validation, teardown, saved engine choice and fallback')
  } finally {
    if (application) await application.close()
    fs.rmSync(directory, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
